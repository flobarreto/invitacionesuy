-- Make the legacy compatibility window explicit and deletion-aware.
--
-- DELETE never removes canonical guests: it retires them, records an audit,
-- preserves attendance_history, and invalidates queued messaging atomically.
-- Once legacy_reads_enabled is false the transition is one-way, dual-write is
-- disabled too, and a permanent BEFORE trigger rejects direct legacy writes.

begin;

alter table public.legacy_migration_audit
  add column if not exists retired_guest_count bigint not null default 0;

create table if not exists public.legacy_rsvp_deletion_audit (
  id bigint generated by default as identity primary key,
  event_id uuid not null references public.events(id) on delete cascade,
  source_table text not null,
  legacy_id_hash text not null,
  guest_id uuid references public.guests(id) on delete set null,
  group_id uuid references public.invitation_groups(id) on delete set null,
  source_payload_fingerprint text not null,
  source text not null check (source in ('legacy_trigger', 'legacy_reconciliation')),
  outcome text not null check (outcome in ('retired', 'canonical_guest_missing')),
  cancelled_delivery_count integer not null default 0,
  uncertain_delivery_count integer not null default 0,
  cancelled_outbound_job_count integer not null default 0,
  uncertain_outbound_job_count integer not null default 0,
  deleted_at timestamptz not null default now(),
  constraint legacy_rsvp_deletion_audit_fingerprint_format
    check (source_payload_fingerprint ~ '^[a-f0-9]{64}$'),
  constraint legacy_rsvp_deletion_audit_legacy_id_hash_format
    check (legacy_id_hash ~ '^[a-f0-9]{64}$')
);

create index if not exists legacy_rsvp_deletion_audit_event_idx
  on public.legacy_rsvp_deletion_audit(event_id, deleted_at desc);
create index if not exists legacy_rsvp_deletion_audit_guest_idx
  on public.legacy_rsvp_deletion_audit(guest_id, deleted_at desc);

alter table public.legacy_rsvp_deletion_audit enable row level security;

create or replace function public.resolve_deleted_legacy_row_identity(
  p_event_id uuid,
  p_source_table text,
  p_source_payload jsonb
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  stable_id text;
  fingerprint text;
  resolved_legacy_id text;
begin
  if p_event_id is null or nullif(btrim(p_source_table), '') is null or
     p_source_payload is null or jsonb_typeof(p_source_payload) <> 'object' then
    raise exception using errcode = '22023', message = 'invalid_legacy_delete_payload';
  end if;
  stable_id := nullif(btrim(p_source_payload ->> 'id'), '');
  fingerprint := public.legacy_payload_fingerprint(p_source_payload);

  if stable_id is not null then
    select identity.legacy_id into resolved_legacy_id
    from public.legacy_row_identities identity
    where identity.event_id = p_event_id
      and identity.source_table = p_source_table
      and identity.stable_source_id = stable_id
    order by identity.updated_at desc, identity.legacy_id
    limit 1;

    if resolved_legacy_id is null and exists (
      select 1 from public.guests guest
      where guest.event_id = p_event_id
        and guest.legacy_table = p_source_table
        and guest.legacy_id = stable_id
    ) then
      resolved_legacy_id := stable_id;
    end if;
    return resolved_legacy_id;
  end if;

  select identity.legacy_id into resolved_legacy_id
  from public.legacy_row_identities identity
  join public.guests guest
    on guest.event_id = identity.event_id
   and guest.legacy_table = identity.source_table
   and guest.legacy_id = identity.legacy_id
  where identity.event_id = p_event_id
    and identity.source_table = p_source_table
    and identity.current_fingerprint = fingerprint
    and not (guest.metadata ? 'legacy_deleted')
  order by identity.anonymous_ordinal nulls last, identity.legacy_id
  limit 1;

  if resolved_legacy_id is null then
    select guest.legacy_id into resolved_legacy_id
    from public.guests guest
    where guest.event_id = p_event_id
      and guest.legacy_table = p_source_table
      and guest.legacy_id is not null
      and not (guest.metadata ? 'legacy_deleted')
      and public.legacy_payload_fingerprint(guest.metadata -> 'legacy_record') = fingerprint
    order by guest.legacy_id
    limit 1;
  end if;

  return resolved_legacy_id;
end;
$$;

create or replace function public.retire_legacy_guest_from_core(
  p_event_id uuid,
  p_source_table text,
  p_legacy_id text,
  p_source_payload jsonb,
  p_source text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  guest_lookup record;
  guest_row public.guests%rowtype;
  group_row public.invitation_groups%rowtype;
  payload_fingerprint text;
  affected_campaigns uuid[];
  cancelled_deliveries integer := 0;
  uncertain_deliveries integer := 0;
  cancelled_jobs integer := 0;
  uncertain_jobs integer := 0;
  previous_sync_setting text := current_setting('app.legacy_to_core', true);
begin
  if p_event_id is null or nullif(btrim(p_source_table), '') is null or
     p_source_payload is null or jsonb_typeof(p_source_payload) <> 'object' or
     p_source not in ('legacy_trigger', 'legacy_reconciliation') then
    raise exception using errcode = '22023', message = 'invalid_legacy_retirement_payload';
  end if;
  if not (
    public.authorize_legacy_rsvp_relation(p_source_table) ->> 'valid'
  )::boolean or not exists (
    select 1 from public.events event
    where event.id = p_event_id and event.legacy_table_name = p_source_table
  ) then
    raise exception using errcode = '42501', message = 'legacy_source_does_not_match_event';
  end if;

  payload_fingerprint := public.legacy_payload_fingerprint(p_source_payload);
  perform pg_advisory_xact_lock(hashtextextended(p_event_id::text || ':legacy-sync', 0));

  select guest.id, guest.group_id into guest_lookup
  from public.guests guest
  where guest.event_id = p_event_id
    and guest.legacy_table = p_source_table
    and guest.legacy_id = p_legacy_id;

  if not found then
    insert into public.legacy_rsvp_deletion_audit (
      event_id, source_table, legacy_id_hash, source_payload_fingerprint,
      source, outcome
    ) values (
      p_event_id, p_source_table,
      encode(extensions.digest(coalesce(p_legacy_id, ''), 'sha256'), 'hex'),
      payload_fingerprint,
      p_source, 'canonical_guest_missing'
    );
    return jsonb_build_object(
      'legacyId', p_legacy_id,
      'outcome', 'canonical_guest_missing'
    );
  end if;

  select * into group_row
  from public.invitation_groups invitation_group
  where invitation_group.id = guest_lookup.group_id
    and invitation_group.event_id = p_event_id
  for update;
  select * into guest_row
  from public.guests guest
  where guest.id = guest_lookup.id and guest.event_id = p_event_id
  for update;

  if guest_row.metadata ? 'legacy_deleted' then
    return jsonb_build_object(
      'legacyId', p_legacy_id,
      'guestId', guest_row.id,
      'groupId', guest_row.group_id,
      'outcome', 'already_retired'
    );
  end if;

  perform set_config('app.legacy_to_core', 'on', true);

  update public.guests guest set
    attendance_status = 'declined',
    attendance_source = 'legacy',
    table_id = null,
    metadata = (guest.metadata || jsonb_build_object(
      'legacy_deleted', jsonb_build_object(
        'active', true,
        'deletedAt', now(),
        'source', p_source,
        'payloadFingerprint', payload_fingerprint,
        'previousAttendanceStatus', guest.attendance_status,
        'previousTableId', guest.table_id
      )
    )) || jsonb_build_object(
      'legacy_synced', coalesce(guest.metadata -> 'legacy_synced', '{}'::jsonb) ||
        jsonb_build_object(
          'attendance_status', 'declined',
          'table_id', null,
          'table_code', null
        )
    ),
    updated_at = now()
  where guest.id = guest_row.id and guest.event_id = p_event_id;

  with finalized as (
    update public.message_deliveries delivery set
      status = case when delivery.status = 'sending' then 'uncertain' else 'cancelled' end,
      error_code = case
        when delivery.status = 'sending' then 'LEGACY_DELETE_RACE'
        else 'LEGACY_GUEST_DELETED'
      end,
      error_detail = case
        when delivery.status = 'sending'
          then 'Legacy guest was deleted while provider outcome was unknown.'
        else delivery.error_detail
      end,
      failed_at = case when delivery.status = 'sending' then now() else delivery.failed_at end,
      locked_at = null,
      locked_by = null,
      updated_at = now()
    where delivery.group_id = guest_row.group_id
      and delivery.event_id = p_event_id
      and delivery.status in ('queued', 'failed', 'sending')
    returning delivery.campaign_id, delivery.status
  )
  select
    array_agg(distinct campaign_id),
    count(*) filter (where status = 'cancelled')::integer,
    count(*) filter (where status = 'uncertain')::integer
  into affected_campaigns, cancelled_deliveries, uncertain_deliveries
  from finalized;

  with finalized as (
    update public.whatsapp_outbound_jobs outbound_job set
      status = case when outbound_job.status = 'sending' then 'uncertain' else 'cancelled' end,
      error_code = case
        when outbound_job.status = 'sending' then 'LEGACY_DELETE_RACE'
        else 'LEGACY_GUEST_DELETED'
      end,
      failed_at = case when outbound_job.status = 'sending' then now() else outbound_job.failed_at end,
      locked_at = null,
      locked_by = null,
      updated_at = now()
    where outbound_job.group_id = guest_row.group_id
      and outbound_job.event_id = p_event_id
      and outbound_job.status in ('queued', 'failed', 'sending')
    returning outbound_job.status
  )
  select
    count(*) filter (where status = 'cancelled')::integer,
    count(*) filter (where status = 'uncertain')::integer
  into cancelled_jobs, uncertain_jobs
  from finalized;

  update public.whatsapp_conversations conversation set
    state = case when exists (
      select 1 from public.guests active_guest
      where active_guest.group_id = guest_row.group_id
        and active_guest.attendance_status = 'pending'
        and not (active_guest.metadata ? 'legacy_deleted')
    ) then 'review' else 'completed' end,
    current_guest_id = (
      select active_guest.id from public.guests active_guest
      where active_guest.group_id = guest_row.group_id
        and active_guest.attendance_status = 'pending'
        and not (active_guest.metadata ? 'legacy_deleted')
      order by active_guest.created_at, active_guest.id
      limit 1
    ),
    requires_review = exists (
      select 1 from public.guests active_guest
      where active_guest.group_id = guest_row.group_id
        and active_guest.attendance_status = 'pending'
        and not (active_guest.metadata ? 'legacy_deleted')
    ),
    completed_at = case when exists (
      select 1 from public.guests active_guest
      where active_guest.group_id = guest_row.group_id
        and active_guest.attendance_status = 'pending'
        and not (active_guest.metadata ? 'legacy_deleted')
    ) then null else now() end,
    last_outbound_message_id = null,
    updated_at = now()
  where conversation.group_id = guest_row.group_id
    and conversation.event_id = p_event_id
    and conversation.state in (
      'awaiting_attendance', 'awaiting_change_selection', 'review', 'completed'
    );

  if not exists (
    select 1 from public.guests active_guest
    where active_guest.group_id = guest_row.group_id
      and not (active_guest.metadata ? 'legacy_deleted')
  ) then
    update public.invitation_groups invitation_group set
      consent_at = null,
      metadata = invitation_group.metadata || jsonb_build_object(
        'legacy_deleted', jsonb_build_object(
          'active', true,
          'deletedAt', now(),
          'source', p_source,
          'payloadFingerprint', payload_fingerprint,
          'originalConsentAt', invitation_group.consent_at
        )
      ),
      updated_at = now()
    where invitation_group.id = guest_row.group_id
      and invitation_group.event_id = p_event_id;
  end if;

  if affected_campaigns is not null then
    update public.message_campaigns campaign set
      status = 'completed',
      completed_at = coalesce(campaign.completed_at, now()),
      updated_at = now()
    where campaign.id = any(affected_campaigns)
      and campaign.status in ('queued', 'running')
      and not exists (
        select 1 from public.message_deliveries delivery
        where delivery.campaign_id = campaign.id
          and delivery.status in ('queued', 'sending', 'failed')
      );
  end if;

  insert into public.legacy_rsvp_deletion_audit (
    event_id, source_table, legacy_id_hash, guest_id, group_id,
    source_payload_fingerprint, source, outcome,
    cancelled_delivery_count, uncertain_delivery_count,
    cancelled_outbound_job_count, uncertain_outbound_job_count
  ) values (
    p_event_id, p_source_table,
    encode(extensions.digest(coalesce(p_legacy_id, ''), 'sha256'), 'hex'),
    guest_row.id, guest_row.group_id,
    payload_fingerprint, p_source, 'retired',
    cancelled_deliveries, uncertain_deliveries,
    cancelled_jobs, uncertain_jobs
  );

  perform set_config('app.legacy_to_core', coalesce(previous_sync_setting, ''), true);
  return jsonb_build_object(
    'legacyId', p_legacy_id,
    'guestId', guest_row.id,
    'groupId', guest_row.group_id,
    'outcome', 'retired',
    'cancelledDeliveries', cancelled_deliveries,
    'uncertainDeliveries', uncertain_deliveries,
    'cancelledOutboundJobs', cancelled_jobs,
    'uncertainOutboundJobs', uncertain_jobs
  );
exception when others then
  perform set_config('app.legacy_to_core', coalesce(previous_sync_setting, ''), true);
  raise;
end;
$$;

create or replace function public.retire_legacy_rsvp_from_core(
  p_event_id uuid,
  p_source_table text,
  p_source_payload jsonb,
  p_source text
)
returns jsonb
