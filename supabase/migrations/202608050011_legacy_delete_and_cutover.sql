security definer
set search_path = public
as $$
declare
  resolved_legacy_id text;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_event_id::text || ':legacy-sync', 0));
  resolved_legacy_id := public.resolve_deleted_legacy_row_identity(
