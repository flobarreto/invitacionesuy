  );
end;
$$;

create or replace function public.guard_legacy_rsvp_write_window()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  state_row public.event_migration_state%rowtype;
begin
  if not (
    public.authorize_legacy_rsvp_relation(tg_table_name) ->> 'valid'
  )::boolean then
    raise exception using errcode = '55000', message = 'unsafe_legacy_rsvp_relation';
  end if;

  select state.* into state_row
  from public.events event
  join public.event_migration_state state on state.event_id = event.id
  where event.legacy_table_name = tg_table_name;

  if not found then
    raise exception using errcode = '55000', message = 'legacy_event_mapping_missing';
  end if;
  if not state_row.legacy_reads_enabled or not state_row.legacy_dual_write_enabled then
    raise exception using
      errcode = '55000',
      message = 'legacy_writes_disabled_after_cutover';
  end if;

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

create or replace function public.sync_legacy_rsvp_to_core()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  event_row public.events%rowtype;
  sync_result jsonb;
  target_guest_id uuid;
  target_group_id uuid;
  previous_sync_setting text := current_setting('app.legacy_to_core', true);
begin
  if not (
    public.authorize_legacy_rsvp_relation(tg_table_name) ->> 'valid'
  )::boolean then
    raise exception using errcode = '55000', message = 'unsafe_legacy_rsvp_relation';
  end if;

  select event.* into event_row
  from public.events event
  join public.event_migration_state state on state.event_id = event.id
  where event.legacy_table_name = tg_table_name
    and state.legacy_reads_enabled
    and state.legacy_dual_write_enabled;

  if not found then
    if tg_op = 'DELETE' then return old; end if;
    return new;
  end if;

  if tg_op = 'DELETE' then
    perform public.retire_legacy_rsvp_from_core(
      event_row.id,
      tg_table_name,
      to_jsonb(old),
      'legacy_trigger'
    );
    return old;
  end if;

  sync_result := public.sync_legacy_payload_to_core(
    event_row.id,
    tg_table_name,
    to_jsonb(new),
    case when tg_op = 'UPDATE' then to_jsonb(old) else null end,
    null,
    'legacy'
  );
  target_guest_id := nullif(sync_result ->> 'guest_id', '')::uuid;
  target_group_id := nullif(sync_result ->> 'group_id', '')::uuid;

  -- Re-inserting a previously deleted legacy row is an explicit reactivation.
  -- Restore only the consent value captured by the retirement transaction.
  perform set_config('app.legacy_to_core', 'on', true);
  update public.guests guest set
    metadata = guest.metadata - 'legacy_deleted',
    updated_at = now()
  where guest.id = target_guest_id and guest.event_id = event_row.id;
  update public.invitation_groups invitation_group set
    consent_at = case
      when invitation_group.metadata ? 'legacy_deleted'
        then nullif(
          invitation_group.metadata #>> '{legacy_deleted,originalConsentAt}',
          ''
        )::timestamptz
      else invitation_group.consent_at
    end,
    metadata = invitation_group.metadata - 'legacy_deleted',
    updated_at = now()
  where invitation_group.id = target_group_id
    and invitation_group.event_id = event_row.id;
  perform set_config('app.legacy_to_core', coalesce(previous_sync_setting, ''), true);

  return new;
exception when others then
  perform set_config('app.legacy_to_core', coalesce(previous_sync_setting, ''), true);
  raise;
end;
$$;

create or replace function public.migrate_legacy_event(p_event_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
#variable_conflict use_variable
declare
  source_table text;
  source_relation regclass;
  relation_inspection jsonb;
  source_record record;
  sync_result jsonb;
  source_count bigint := 0;
  migrated_count bigint := 0;
  retired_count bigint := 0;
  source_checksum text;
  target_checksum text;
  seen_legacy_ids text[] := '{}'::text[];
  ambiguities jsonb := '[]'::jsonb;
  migration_status text;
  previous_sync_setting text := current_setting('app.legacy_to_core', true);
begin
  select event.legacy_table_name into source_table
  from public.events event
  join public.event_migration_state state on state.event_id = event.id
  where event.id = p_event_id and state.legacy_reads_enabled;

  if source_table is null then
    raise exception using errcode = '22023', message = 'legacy_event_not_available';
  end if;

  relation_inspection := public.authorize_legacy_rsvp_relation(source_table);
  if not (relation_inspection ->> 'valid')::boolean then
    insert into public.legacy_rsvp_mapping_reviews (
      event_id, candidate_table_name, source, reason, diagnostics
    ) values (
      p_event_id, source_table, 'events.legacy_table_name',
      relation_inspection ->> 'reason', relation_inspection
    ) on conflict do nothing;

    insert into public.legacy_migration_audit (
      event_id, source_table, status, ambiguities
    ) values (
      p_event_id,
      source_table,
      case when relation_inspection ->> 'reason' = 'relation_missing'
        then 'source_missing' else 'failed' end,
      jsonb_build_array(jsonb_build_object(
        'reason', 'unsafe_legacy_relation',
        'inspection', relation_inspection
      ))
    );
    return jsonb_build_object(
      'event_id', p_event_id,
      'source_table', source_table,
      'status', case when relation_inspection ->> 'reason' = 'relation_missing'
        then 'source_missing' else 'failed' end,
      'inspection', relation_inspection
    );
  end if;

  source_relation := to_regclass(format('%I.%I', 'public', source_table));
  execute format('lock table %s in share mode', source_relation);
  perform pg_advisory_xact_lock(hashtextextended(p_event_id::text || ':legacy-sync', 0));
  perform set_config('app.legacy_to_core', 'on', true);

  execute format(
    'select count(*), md5(coalesce(string_agg(md5(to_jsonb(t)::text), '''' order by md5(to_jsonb(t)::text)), '''')) from %s t',
    source_relation
  ) into source_count, source_checksum;

  for source_record in execute format($query$
    with source_rows as (
      select
        to_jsonb(t) as payload,
        public.legacy_payload_fingerprint(to_jsonb(t)) as fingerprint
      from %s t
    )
    select
      payload,
      row_number() over (
        partition by fingerprint
        order by payload::text
      )::integer as occurrence
    from source_rows
    order by
      case when nullif(btrim(payload ->> 'id'), '') is null then 1 else 0 end,
      coalesce(nullif(btrim(payload ->> 'id'), ''), fingerprint),
      payload::text
  $query$, source_relation)
  loop
    sync_result := public.sync_legacy_payload_to_core(
      p_event_id,
      source_table,
      source_record.payload,
      null,
      source_record.occurrence,
      'legacy_migration'
    );
    seen_legacy_ids := array_append(seen_legacy_ids, sync_result ->> 'legacy_id');
    ambiguities := ambiguities || coalesce(sync_result -> 'ambiguities', '[]'::jsonb);

    -- A row that disappeared and later returned is active again.
    update public.guests guest set
      metadata = guest.metadata - 'legacy_deleted',
      updated_at = now()
    where guest.id = (sync_result ->> 'guest_id')::uuid
      and guest.event_id = p_event_id;
    update public.invitation_groups invitation_group set
      consent_at = case
        when invitation_group.metadata ? 'legacy_deleted'
          then nullif(
            invitation_group.metadata #>> '{legacy_deleted,originalConsentAt}',
            ''
          )::timestamptz
        else invitation_group.consent_at
      end,
      metadata = invitation_group.metadata - 'legacy_deleted',
      updated_at = now()
    where invitation_group.id = (sync_result ->> 'group_id')::uuid
      and invitation_group.event_id = p_event_id;
  end loop;

  -- Reconcile a missed trigger/delta: canonical identities absent from the
  -- locked source are retired rather than deleted.
  for source_record in
    select
      guest.legacy_id,
      coalesce(guest.metadata -> 'legacy_record', identity.last_legacy_payload) as payload
    from public.guests guest
    left join public.legacy_row_identities identity
      on identity.event_id = guest.event_id
     and identity.source_table = guest.legacy_table
     and identity.legacy_id = guest.legacy_id
    where guest.event_id = p_event_id
      and guest.legacy_table = source_table
      and guest.legacy_id is not null
      and not (guest.metadata ? 'legacy_deleted')
      and not (guest.legacy_id = any(seen_legacy_ids))
    order by guest.legacy_id
  loop
    sync_result := public.retire_legacy_guest_from_core(
      p_event_id,
      source_table,
      source_record.legacy_id,
      source_record.payload,
      'legacy_reconciliation'
    );
    if sync_result ->> 'outcome' = 'retired' then
      retired_count := retired_count + 1;
    end if;
  end loop;

  select
    count(*),
    md5(coalesce(string_agg(
      md5((guest.metadata -> 'legacy_record')::text),
      '' order by md5((guest.metadata -> 'legacy_record')::text)
    ), ''))
  into migrated_count, target_checksum
  from public.guests guest
  where guest.event_id = p_event_id
    and guest.legacy_table = source_table
    and not (guest.metadata ? 'legacy_deleted');

  migration_status := case
    when source_count = migrated_count and source_checksum = target_checksum then 'completed'
    else 'failed'
  end;
  if migration_status = 'failed' then
    ambiguities := ambiguities || jsonb_build_array(jsonb_build_object(
      'reason', 'source_target_mismatch',
      'source_count', source_count,
      'target_count', migrated_count,
      'source_checksum', source_checksum,
      'target_checksum', target_checksum
    ));
  end if;

  insert into public.legacy_migration_audit (
    event_id, source_table, source_count, migrated_guest_count,
    retired_guest_count, source_checksum, target_checksum, status, ambiguities
  ) values (
    p_event_id, source_table, source_count, migrated_count,
    retired_count, source_checksum, target_checksum, migration_status, ambiguities
  );

  perform set_config('app.legacy_to_core', coalesce(previous_sync_setting, ''), true);

  return jsonb_build_object(
    'event_id', p_event_id,
    'source_table', source_table,
    'status', migration_status,
    'source_count', source_count,
    'migrated_guest_count', migrated_count,
    'retired_guest_count', retired_count,
    'source_checksum', source_checksum,
    'target_checksum', target_checksum,
    'ambiguities', ambiguities
  );
exception when others then
  perform set_config('app.legacy_to_core', coalesce(previous_sync_setting, ''), true);
  insert into public.legacy_migration_audit (
    event_id, source_table, source_count, migrated_guest_count,
    retired_guest_count, source_checksum, target_checksum, status, ambiguities
  ) values (
    p_event_id, coalesce(source_table, '<unknown>'), source_count, migrated_count,
    retired_count, source_checksum, target_checksum, 'failed',
    jsonb_build_array(jsonb_build_object('reason', sqlstate))
  );
  return jsonb_build_object(
    'event_id', p_event_id,
    'source_table', coalesce(source_table, '<unknown>'),
    'status', 'failed',
    'reason', sqlstate
  );
end;
$$;

create or replace function public.normalize_legacy_event_cutover_state()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'UPDATE' and not old.legacy_reads_enabled and new.legacy_reads_enabled then
    raise exception using errcode = '55000', message = 'legacy_cutover_is_one_way';
  end if;
  if not new.legacy_reads_enabled then
    new.legacy_dual_write_enabled := false;
    new.cutover_completed_at := coalesce(new.cutover_completed_at, now());
  end if;
  new.updated_at := now();
  return new;
end;
$$;

update public.event_migration_state state set
  legacy_dual_write_enabled = false,
  cutover_completed_at = coalesce(state.cutover_completed_at, now()),
  updated_at = now()
where not state.legacy_reads_enabled;

alter table public.event_migration_state
  drop constraint if exists event_migration_state_cutover_disables_legacy_writes;
alter table public.event_migration_state
  add constraint event_migration_state_cutover_disables_legacy_writes
  check (legacy_reads_enabled or not legacy_dual_write_enabled);

drop trigger if exists event_migration_state_normalize_cutover
  on public.event_migration_state;
create trigger event_migration_state_normalize_cutover
before insert or update of legacy_reads_enabled, legacy_dual_write_enabled
  on public.event_migration_state
for each row execute function public.normalize_legacy_event_cutover_state();

create or replace function public.complete_legacy_event_cutover(p_event_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  event_row public.events%rowtype;
  state_row public.event_migration_state%rowtype;
  audit_row public.legacy_migration_audit%rowtype;
  source_relation regclass;
  relation_inspection jsonb;
  current_source_count bigint;
  current_source_checksum text;
begin
  select * into event_row
  from public.events
  where id = p_event_id
  for update;
  if not found or event_row.legacy_table_name is null then
    raise exception using errcode = 'P0002', message = 'legacy_event_not_found';
  end if;

  relation_inspection := public.authorize_legacy_rsvp_relation(event_row.legacy_table_name);
  if not (relation_inspection ->> 'valid')::boolean then
    raise exception using
      errcode = '55000',
      message = 'unsafe_legacy_rsvp_relation',
      detail = relation_inspection::text;
  end if;

  select * into state_row
  from public.event_migration_state
  where event_id = p_event_id
  for update;
  if not found then
    raise exception using errcode = 'P0002', message = 'migration_state_not_found';
  end if;
  if not state_row.legacy_reads_enabled then
    update public.event_migration_state set
      legacy_dual_write_enabled = false,
      cutover_completed_at = coalesce(cutover_completed_at, now()),
      updated_at = now()
    where event_id = p_event_id
    returning * into state_row;
    execute format(
      'drop trigger if exists invitia_legacy_dual_write on public.%I',
      event_row.legacy_table_name
    );
    return jsonb_build_object(
      'eventId', p_event_id,
      'legacyReadsEnabled', false,
      'legacyDualWriteEnabled', false,
      'idempotentReplay', true,
      'cutoverCompletedAt', state_row.cutover_completed_at
    );
  end if;

  source_relation := to_regclass(format('%I.%I', 'public', event_row.legacy_table_name));
  if source_relation is null then
    raise exception using errcode = '55000', message = 'legacy_source_missing_at_cutover';
  end if;
  execute format('lock table %s in share mode', source_relation);
  perform pg_advisory_xact_lock(hashtextextended(p_event_id::text || ':legacy-sync', 0));

  select * into audit_row
  from public.legacy_migration_audit
  where event_id = p_event_id
  order by migrated_at desc, id desc
  limit 1;

  if not found or audit_row.status <> 'completed' or
     audit_row.source_count <> audit_row.migrated_guest_count or
     audit_row.source_checksum is distinct from audit_row.target_checksum or
     jsonb_typeof(audit_row.ambiguities) <> 'array' or
     jsonb_array_length(audit_row.ambiguities) > 0 then
    raise exception using
      errcode = '55000',
      message = 'legacy_cutover_audit_not_clean',
      hint = 'Resolve migration ambiguities and rerun migrate_legacy_event before cutover.';
  end if;

  execute format(
    'select count(*), md5(coalesce(string_agg(md5(to_jsonb(t)::text), '''' order by md5(to_jsonb(t)::text)), '''')) from %s t',
    source_relation
  ) into current_source_count, current_source_checksum;

  if current_source_count <> audit_row.source_count or
     current_source_checksum is distinct from audit_row.source_checksum then
    raise exception using
      errcode = '40001',
      message = 'legacy_source_changed_after_audit',
      hint = 'Run migrate_legacy_event again before cutover.';
  end if;

  update public.event_migration_state set
    legacy_reads_enabled = false,
    legacy_dual_write_enabled = false,
    cutover_completed_at = coalesce(cutover_completed_at, now()),
    updated_at = now()
  where event_id = p_event_id
  returning * into state_row;

  execute format(
    'drop trigger if exists invitia_legacy_dual_write on public.%I',
    event_row.legacy_table_name
  );

  return jsonb_build_object(
    'eventId', p_event_id,
    'legacyReadsEnabled', false,
    'legacyDualWriteEnabled', false,
    'idempotentReplay', false,
    'cutoverCompletedAt', state_row.cutover_completed_at,
    'sourceCount', audit_row.source_count,
    'checksum', audit_row.source_checksum
  );
end;
$$;

do $$
declare
  event_record record;
begin
  for event_record in
    select event.id, event.legacy_table_name,
           state.legacy_reads_enabled, state.legacy_dual_write_enabled
    from public.events event
    join public.event_migration_state state on state.event_id = event.id
    where event.legacy_table_name is not null
  loop
    if (
      public.authorize_legacy_rsvp_relation(event_record.legacy_table_name)
        ->> 'valid'
    )::boolean then
      execute format(
        'drop trigger if exists invitia_legacy_write_guard on public.%I',
        event_record.legacy_table_name
      );
      execute format(
        'create trigger invitia_legacy_write_guard before insert or update or delete on public.%I for each row execute function public.guard_legacy_rsvp_write_window()',
        event_record.legacy_table_name
      );
      execute format(
        'drop trigger if exists invitia_legacy_dual_write on public.%I',
        event_record.legacy_table_name
      );
      if event_record.legacy_reads_enabled and event_record.legacy_dual_write_enabled then
        execute format(
          'create trigger invitia_legacy_dual_write after insert or update or delete on public.%I for each row execute function public.sync_legacy_rsvp_to_core()',
          event_record.legacy_table_name
        );
      end if;
    end if;
  end loop;
end;
$$;

